"""Command-line interface: ``streamwise-experiment <command>`` (see ``--help``)."""

from __future__ import annotations

import argparse
import asyncio
import sys
import time
from pathlib import Path

from streamwise.experiments.runner import ExperimentConfig, run_experiment
from streamwise.experiments.traces import fluctuating_trace, write_trace


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="streamwise-experiment")
    sub = parser.add_subparsers(dest="command", required=True)

    run = sub.add_parser("run", help="run an experiment and build its report")
    run.add_argument("config", type=Path, help="experiment TOML file")
    run.add_argument("--out", type=Path, help="output directory (default: results/<name>-<time>)")
    run.add_argument("--no-report", action="store_true")

    report = sub.add_parser("report", help="(re)build the report of a finished experiment")
    report.add_argument("out", type=Path, help="experiment output directory")
    report.add_argument("--media-dir", type=Path, default=Path("media"))

    gen = sub.add_parser("gen-trace", help="generate a fluctuating bandwidth trace")
    gen.add_argument("out", type=Path)
    gen.add_argument("--seed", type=int, default=7)
    gen.add_argument("--duration", type=float, default=400.0)
    gen.add_argument("--mean-mbps", type=float, default=3.5)
    bench = sub.add_parser("crypto-bench", help="measure the cost of AES-256-GCM encryption")
    bench.add_argument("--media-dir", type=Path, default=Path("media"))
    bench.add_argument("--video", default="bbb")
    bench.add_argument("--out", type=Path, help="also write the result to this Markdown file")
    win = sub.add_parser("window-bench", help="evaluate the sliding-window transport")
    win.add_argument("--media-dir", type=Path, default=Path("media"))
    win.add_argument("--out", type=Path, default=Path("results/window-bench"))
    win.add_argument("--rtt-video", default="bbb", help="video for the window/RTT sweep")
    win.add_argument("--long-video", default="bbblong", help="video for the fault experiment")
    win.add_argument("--rate-mbps", type=float, default=20.0, help="link rate of the RTT sweep")
    win.add_argument(
        "--fault-rate-mbps", type=float, default=4.0, help="link rate of the fault experiment"
    )
    win.add_argument(
        "--reset-after-s",
        type=float,
        action="append",
        help="connection lifetime(s) to test, repeatable (default: 30 and 10, plus no resets)",
    )
    win.add_argument("--skip-rtt", action="store_true")
    win.add_argument("--skip-faults", action="store_true")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if args.command == "gen-trace":
        points = fluctuating_trace(args.seed, args.duration, args.mean_mbps)
        write_trace(
            args.out,
            points,
            f"Fluctuating trace: seed={args.seed}, duration={args.duration}s, "
            f"mean={args.mean_mbps} Mbit/s\nGenerated by: streamwise-experiment gen-trace",
        )
        print(f"wrote {len(points)} points to {args.out}")
        return 0

    if args.command == "crypto-bench":
        from streamwise.experiments.cryptobench import run

        text = run(args.media_dir, args.video)
        print(text, end="")
        if args.out:
            args.out.parent.mkdir(parents=True, exist_ok=True)
            args.out.write_text(text)
        return 0

    if args.command == "window-bench":
        from streamwise.experiments.windowbench import run as run_window_bench

        resets = (None, *(args.reset_after_s or (30.0, 10.0)))
        summary = run_window_bench(
            args.media_dir,
            args.out,
            args.rtt_video,
            args.long_video,
            args.rate_mbps,
            args.fault_rate_mbps,
            resets,
            args.skip_rtt,
            args.skip_faults,
        )
        print(summary.read_text(), end="")
        return 0

    from streamwise.experiments.report import build_report  # matplotlib is slow to import

    if args.command == "report":
        print(f"report: {build_report(args.out, args.media_dir)}")
        return 0

    config = ExperimentConfig.load(args.config)
    out = args.out or Path("results") / f"{args.config.stem}-{time.strftime('%Y%m%d-%H%M%S')}"
    started = time.monotonic()
    runs = asyncio.run(run_experiment(config, args.config, out))
    failed = [r for r in runs if r.exit_code != 0]
    print(
        f"finished {len(runs)} sessions in {time.monotonic() - started:.0f}s, {len(failed)} failed"
    )
    if not args.no_report:
        print(f"report: {build_report(out, Path(config.media_dir))}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
